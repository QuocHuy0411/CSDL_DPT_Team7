"""Read-only audit of locked corpus, current serving indexes and annotation integrity.

Writes only a verification JSON. Pending human labels are reported, never generated.
Use --raw to additionally rehash every original TXT (may take longer on HDD).
"""

from __future__ import annotations

import argparse
from collections import Counter
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import unicodedata

from engine.preprocessing import ROOT
from scripts.annotate import load_context
from scripts.build_indexes import load_corpus, write_json
from scripts.search import load_engine

ORIGINAL_RAW_SHA256 = "76d541105d7ce1ad4c561d8cf7e875c4a3e5451ff6d139f283bf7d5eaa88701f"


def audit(*, include_raw=False):
    documents, corpus_sha = load_corpus(ROOT / "data/corpus.jsonl", ROOT / "data/corpus_manifest.json")
    by_id = {d["doc_id"]: d for d in documents}
    for d in documents:
        source = (ROOT / "data/raw" / d["metadata"]["source_file"]).resolve()
        if not source.is_relative_to((ROOT / "data/raw").resolve()):
            raise ValueError("Unsafe source_file path")
        normalized = " ".join(unicodedata.normalize("NFC", source.read_text(encoding="utf-16")).split())
        assert normalized == d["content"], d["doc_id"]
        md5 = hashlib.md5(normalized.encode("utf-8")).hexdigest()
        assert md5 == d["metadata"]["content_md5"]
        assert d["doc_id"] == "vn_" + md5[:16]
        assert len(normalized.split()) >= 100
    queries_bytes = (ROOT / "data/queries.json").read_bytes()
    queries_sha = hashlib.sha256(queries_bytes).hexdigest()
    queries = json.loads(queries_bytes)["queries"]
    assert len(queries) == 20 and set(Counter(q["category"] for q in queries).values()) == {2}
    configs = {}
    for configuration in ("C1", "C2", "C3", "C4"):
        engine = load_engine(ROOT / "data/indexes" / configuration)
        assert engine.metadata["corpus_sha256"] == corpus_sha
        assert engine.metadata["configuration"] == configuration
        assert engine.n_documents == 2500
        checked, max_delta, empty = 0, 0.0, []
        for query in queries:
            hits = engine.search(query["text"], top_k=10)
            if not hits:
                empty.append(query["query_id"])
            for hit in hits:
                assert hit["doc_id"] in by_id and hit["score"] > 0
                detail = engine.explain(query["text"], hit["doc_id"])
                delta = abs(sum(c["contribution"] for c in detail["contributions"]) - hit["score"])
                assert delta < 1e-12
                max_delta = max(max_delta, delta)
                checked += 1
        configs[configuration] = {"checked_search_explain_pairs": checked,
                                   "max_cosine_decomposition_error": max_delta,
                                   "empty_queries": empty,
                                   "preprocessing_status": engine.metadata["preprocessing_status"],
                                   "preprocessing_fingerprint": engine.metadata["preprocessing"]["fingerprint"]}
    pool, qrels, index = load_context(ROOT / "data/ground_truth/mm/pool.json",
                                      ROOT / "data/ground_truth/mm/qrels.json")
    assert pool["corpus_sha256"] == corpus_sha and pool["queries_sha256"] == queries_sha
    assert pool["search_engine_parity"]["status"] == "passed"
    for pair in pool["pairs"]:
        assert pair["content"] == by_id[pair["doc_id"]]["content"]
    result = {"schema_version": 1, "created_utc": datetime.now(timezone.utc).isoformat(),
              "technical_integrity": "passed", "corpus_sha256": corpus_sha,
              "queries_sha256": queries_sha, "documents_checked_against_raw": len(documents),
              "category_counts": dict(Counter(d["category"] for d in documents)),
              "configurations": configs, "pool_pairs": len(index),
              "human_judgments_confirmed": sum(r["status"] == "confirmed" for r in index.values()),
              "quality_metrics": "not generated by integrity audit"}
    if include_raw:
        raw = ROOT / "data/raw"
        digest = hashlib.sha256()
        paths = sorted(raw.rglob("*.txt"), key=lambda p: p.relative_to(raw).as_posix())
        for path in paths:
            payload = path.read_bytes()
            assert payload[:2] == b"\xff\xfe"
            digest.update(path.relative_to(raw).as_posix().encode("utf-8") + b"\0")
            digest.update(hashlib.sha256(payload).digest())
        actual = digest.hexdigest()
        assert actual == ORIGINAL_RAW_SHA256, "Raw changed since initial read-only survey"
        result["raw"] = {"txt_files": len(paths), "sha256": actual, "unchanged": True}
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", action="store_true")
    parser.add_argument("--out", type=Path, default=ROOT / "results/release_audit.json")
    args = parser.parse_args()
    result = audit(include_raw=args.raw)
    write_json(args.out, result)
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
